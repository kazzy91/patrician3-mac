// module.h - the tables recomp/p3_build.py generates for each translated module (out/build/<module>/table.c).
#pragma once
#include <stdint.h>

#include "runtime.h"

typedef struct { uint32_t slot; const char *name; } ImportSlot;       // IAT slot address, "DLL!function"
typedef struct { const char *name; uint32_t addr; } ExportEntry;
typedef struct {
    const char *name;            // module name (symbol prefix), e.g. "p3", "archiver"
    const char *file;            // file name in the game folder, e.g. "Patrician3.exe"
    uint32_t base, entry;
    const uint32_t *func_addr;   // translated functions, sorted by address
    void (*const *func_ptr)(Cpu *);
    unsigned func_count;
    const ImportSlot *imports;   // sorted by slot
    unsigned import_count;
    const ExportEntry *exports;  // sorted by name, terminated by {0, 0}
    unsigned export_count;
} ModuleTables;

// out/build/modules.c (generated by runtime/build.sh): every linked module, the exe first.
extern const ModuleTables *const all_modules[];
extern const unsigned module_count;

// boot.c
const ModuleTables *module_by_name(const char *name);     // "Archiver.dll", "archiver", case-insensitive; NULL if absent
const ModuleTables *module_by_base(uint32_t base);
uint32_t module_export(const ModuleTables *m, const char *name_or_ordinal);   // 0 if absent
